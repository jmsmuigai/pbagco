import { $, $$, api, esc } from './app.js';
let kind = 'tagline';
$$('[data-k]').forEach((b) => b.addEventListener('click', () => { kind = b.dataset.k; $$('[data-k]').forEach((x) => x.setAttribute('aria-selected', x === b)); }));
$('#spark').addEventListener('submit', async (e) => {
  e.preventDefault();
  const out = $('#sparkOut'), btn = $('#spark button.btn');
  out.className = 'spark-out loading'; out.textContent = 'Writing…'; btn.disabled = true;
  try {
    const r = await api('/api/ai/spark', { method: 'POST', body: { kind, topic: $('#topic').value } });
    out.className = 'spark-out'; out.innerHTML = esc(r.text) + (r.offline ? '\n\n<small class="muted">(sample output — live Gemini responses appear once the API key is connected)</small>' : `\n\n<small class="muted">Generated by ${esc(r.model || 'Gemini')} · always review AI output before publishing</small>`);
  } catch (err) { out.className = 'spark-out'; out.textContent = err.message; }
  btn.disabled = false;
});
